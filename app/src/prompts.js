export function friendlyAnalyzeError(message) {
  const text = String(message || '');
  if (/temperature/i.test(text)) return '当前模型参数不兼容，请重试或更换模型。';
  if (/files|上传失败|file id/i.test(text)) return '视频准备失败，请检查连接后重试。';
  if (/video_url|ms:\/\/|不支持.*视频|vision/i.test(text)) return '当前模型不能直接理解视频，请更换支持视频的模型。';
  if (/network|fetch|连接|timeout|超时/i.test(text)) return '连接中断，请检查服务后重试。';
  if (/json|parse|格式/i.test(text)) return '结果整理失败，可以重试一次。';
  return '这次没有解析成功，请重试。';
}

const ENTITY_DICT = ['小猫','猫咪','橘猫','奶牛猫','小狗','狗狗','幼犬','田园犬','金毛','柯基','柴犬','猫','狗','犬','兔子','仓鼠','鹦鹉','牵引绳','项圈','胸背带','猫砂盆','猫爬架','狗粮','猫粮','冻干','零食','罐头','玩具','逗猫棒','飞盘','餐桌','沙发','地毯','浴室','毛巾','吹风机','指甲剪','航空箱','饮水机','水碗','食盆','草地','公园','石板路','汽车','车位','主人','小朋友','尾巴','爪子','耳朵'];
export const ENTITY_SCAN = [...ENTITY_DICT].sort((a, b) => b.length - a.length);

/* 增量扫描文本，返回新点亮的实体（带去重：已亮"猫咪"不再亮"猫"） */
export function scanEntities(text, found) {
  const added = [];
  for (const w of ENTITY_SCAN) {
    if (found.has(w) || !text.includes(w)) continue;
    let dup = false;
    for (const f of found) { if (f.includes(w) || w.includes(f)) { dup = true; break; } }
    found.add(w);
    if (!dup) added.push(w);
  }
  return added;
}
